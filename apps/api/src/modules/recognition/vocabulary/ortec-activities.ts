/**
 * Активности, которые означают отсутствие на работе, а не смену.
 *
 * В PDF-выгрузке отпуск и выходной по коллективному договору занимают ту же
 * строку таблицы, что и смена, и у них есть время: отпускной день записан как
 * `09.00 - 15.00`, потому что так он засчитывается в баланс часов. По времени
 * такая строка неотличима от рабочей, и без этого списка в календаре появилось
 * бы четыре события «Работа 09:00–15:00» на дни, когда человек в отпуске.
 *
 * Список закрытый и сравнивается точно: текст в PDF настоящий, ошибок чтения в
 * нём не бывает, а нечёткое сравнение здесь только создало бы ложные
 * срабатывания на названиях рабочих участков.
 *
 * Незнакомый вид отсутствия сюда не попадёт и уедет в ревью обычной сменой —
 * человек увидит её вместе с названием активности и снимет галочку. Тогда же
 * название добавляется в этот список.
 */
export const NON_WORK_ACTIVITIES = [
  // встречались в реальных выгрузках
  'Vuosiloma', // ежегодный отпуск
  'TES V', // свободный день по коллективному договору (TES vapaa)

  // стандартные финские термины, добавлены на будущее
  'Sairausloma', // больничный
  'Palkaton vapaa', // отпуск без содержания
  'Arkipyhä', // праздничный будний день
] as const;

const NORMALIZED = new Set(NON_WORK_ACTIVITIES.map(normalize));

function normalize(value: string): string {
  return value.trim().replace(/\s+/g, ' ').toLowerCase();
}

/** Означает ли название активности отсутствие на работе. */
export function isNonWorkActivity(name: string): boolean {
  return NORMALIZED.has(normalize(name));
}
